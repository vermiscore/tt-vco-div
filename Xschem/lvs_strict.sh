#!/bin/bash
# Generic LVS runner for SKY130: KLayout flatten -> Magic extract -> netgen compare
# strict: extract unique (no connect-by-label), property errors = FAIL, missing exclude cell = FAIL
# Usage: put this script in the layout directory and run ./lvs.sh
set -u

PDK=${SKY130A:-/home/user/.volare/volare/sky130/versions/0fe599b2afb6708d281543108caf8310912f54af/sky130A}
[ -d "$PDK" ] || { echo "PDK not found: $PDK"; exit 1; }

# Interactive picker: pick "prompt" choice1 choice2 ...  -> result in $PICKED
pick() {
  local prompt=$1; shift
  if [ $# -eq 0 ]; then echo "*** no candidates for: $prompt"; exit 1; fi
  if [ $# -eq 1 ]; then PICKED=$1; echo "$prompt: $1 (only one)"; return; fi
  echo "$prompt"
  PS3="number> "
  select f in "$@"; do [ -n "$f" ] && { PICKED=$f; break; }; done
}

# 1. layout GDS (skip generated flat files)
mapfile -t GDS_LIST < <(ls *.gds 2>/dev/null | grep -v '_flat\.gds$')
pick "Layout GDS" "${GDS_LIST[@]}"
GDS_ABS=$(realpath "$PICKED")

# 2. top cell (read cell names from the GDS)
TMP=$(mktemp -d)
cat > "$TMP/cells.py" << EOF
import pya
ly = pya.Layout()
ly.read("$GDS_ABS")
for c in ly.top_cells():
    print(c.name)
EOF
mapfile -t CELLS < <(klayout -b -r "$TMP/cells.py" < /dev/null 2>/dev/null)
rm -rf "$TMP"
pick "Top cell" "${CELLS[@]}"
CELL=$PICKED

# 2b. cells to exclude from LVS (e.g. inductor: pure metal, would short its terminals)
echo "Cells to exclude from LVS (e.g. the inductor cell), space separated."
echo "Leave empty for none."
read -r -p "exclude> " EXCLUDE

# 3. schematic netlist from xschem (skip files generated by this script)
mapfile -t SCH_LIST < <(ls ./*.spice ../simulation/*.spice ../*.spice 2>/dev/null \
  | grep -v -e '_sch\.spice$' -e '_lay\.spice$')
pick "Schematic netlist" "${SCH_LIST[@]}"
SCH_ABS=$(realpath "$PICKED")

# Work dir keeps generated files (.mag/.ext etc.) away from your files
WORK="lvs_${CELL}"
rm -rf "$WORK"; mkdir "$WORK"; cd "$WORK"

# 4. prepare schematic: enable .subckt/.ends, resistor XR* -> R* (primitive)
cp "$SCH_ABS" sch.spice
# xschem comments the header as "**.subckt" and its continuation lines as "*+"
sed -i -e 's/^\*\*\.subckt/.subckt/' -e 's/^\*+/+/' -e 's/^\*\*\.ends/.ends/' -e 's/^XR/R/' sch.spice
if [ -n "$EXCLUDE" ]; then
  # excluded layout cells are assumed to be inductors -> remove L elements from schematic
  echo "=== excluded from LVS: $EXCLUDE  (schematic L* elements removed)"
  sed -i '/^[Ll]/d' sch.spice
fi
SCH_CELL=$(awk 'tolower($1)==".subckt"{print $2; exit}' sch.spice)
[ -n "$SCH_CELL" ] || { echo "*** no .subckt in schematic netlist"; exit 1; }

# 5. flatten (so lvtn etc. drawn in parent applies to devices in subcells)
cat > flat.py << EOF
import pya
ly = pya.Layout()
ly.read("$GDS_ABS")
for name in "$EXCLUDE".split():
    c = ly.cell(name)
    if c is None:
        print("*** exclude: cell not found:", name)
    else:
        ly.delete_cell(c.cell_index())
ly.cell("$CELL").flatten(-1, True)
ly.write("flat.gds")
EOF
klayout -b -r flat.py < /dev/null > klayout.log 2>&1
[ -f flat.gds ] || { echo "*** flatten failed (see $WORK/klayout.log)"; exit 1; }
grep "exclude: cell not found" klayout.log && { echo "*** exclude cell not found"; exit 1; }

# 6. extract with Magic (labels -> ports)
magic -dnull -noconsole -rcfile "$PDK/libs.tech/magic/sky130A.magicrc" > magic.log 2>&1 << EOF
gds read flat.gds
load $CELL
select top cell
port makeall
extract unique
extract all
ext2spice lvs
ext2spice -o lay.spice
quit -noprompt
EOF
[ -f lay.spice ] || { echo "*** extraction failed (see $WORK/magic.log)"; exit 1; }

# Magic's "port makeall" does not turn every label into a port, which breaks
# pin matching on symmetric circuits. Use the schematic pin list for the layout
# subckt, keeping only names that exist as labeled nets in the layout.
# read the subckt header including "+" continuation lines
subckt_pins() {  # $1=file $2=cell
  awk -v c="$2" '
    f && /^\+/ {sub(/^\+/, ""); printf " %s", $0; next}
    f {exit}
    tolower($1)==".subckt" && $2==c {f=1; $1=$2=""; printf "%s", $0}
    END {print ""}' "$1"
}
SCH_PINS=$(subckt_pins sch.spice "$SCH_CELL")
LAY_PINS=""
for p in $SCH_PINS; do
  # literal match: names like ua[0] contain [ ] (regex chars)
  if awk -v p="$p" '{for(i=1;i<=NF;i++) if($i==p){f=1; exit}} END{exit !f}' lay.spice; then
    LAY_PINS="$LAY_PINS $p"
  else
    echo "*** pin '$p': no layout net with this name (label missing or not on metal)"
  fi
done
awk -v c="$CELL" -v pins="$LAY_PINS" '
  skip && /^\+/ {next}
  {skip=0}
  tolower($1)==".subckt" && $2==c && !done {print ".subckt " c pins; done=1; skip=1; next}
  {print}' lay.spice > lay.tmp && mv lay.tmp lay.spice

# Drop diffusion area/perimeter params: they differ between edge and inner
# fingers in layout and mislead netgen's "resolve symmetries by property value".
for f in lay.spice sch.spice; do
  sed -i -E -e "s/ (ad|as|pd|ps|nrd|nrs)='[^']*'//g" \
            -e "s/ (ad|as|pd|ps|nrd|nrs)=[^ ']+//g" "$f"
done

# Schematic sanity checks + size comparison (python helper)
cat > check.py << 'PYEOF'
# Schematic sanity checks + size comparison (schematic vs layout)
import sys
from collections import defaultdict, Counter

def logical_lines(fn):
    out = []
    for raw in open(fn):
        raw = raw.rstrip("\n")
        if raw.startswith("+") and out:
            out[-1] += " " + raw[1:]
        else:
            out.append(raw)
    return out

def num(v, default=None):
    try:
        return float(v)
    except (TypeError, ValueError):
        return default

def parse(fn, cell):
    pins, devs, inside = [], [], False
    for ln in logical_lines(fn):
        t = ln.split()
        if not t or t[0].startswith("*"):
            continue
        k = t[0].lower()
        if k == ".subckt":
            inside = (t[1] == cell)
            if inside:
                pins = t[2:]
            continue
        if k == ".ends":
            inside = False
            continue
        if not inside or t[0][0].upper() not in "XMR":
            continue
        nodes, p = [], {}
        for tok in t[1:]:
            if "=" in tok:
                a, b = tok.split("=", 1)
                p[a.lower()] = b
            else:
                nodes.append(tok)
        devs.append({"name": t[0], "model": nodes[-1], "nodes": nodes[:-1], "p": p})
    return pins, devs

def mos_info(d):
    p = d["p"]
    w, l = num(p.get("w")), num(p.get("l"))
    nf = num(p.get("nf"), 1.0) or 1.0
    m, mult = num(p.get("m")), num(p.get("mult"))
    cnt = m if m is not None else (mult if mult is not None else 1.0)
    wf = w / nf if w is not None else None
    return w, l, nf, m, mult, cnt, wf

def fmt(x):
    return "-" if x is None else ("%g" % x)

lay_fn, sch_fn, lay_cell, sch_cell = sys.argv[1:5]
lpins, ldevs = parse(lay_fn, lay_cell)
spins, sdevs = parse(sch_fn, sch_cell)

warn = []

# --- pins
dup = [p for p, c in Counter(spins).items() if c > 1]
if dup:
    warn.append("duplicate pins in schematic .subckt: " + " ".join(dup))

# --- per-net connection count (dangling nets)
netcnt = Counter()
for d in sdevs:
    for n in d["nodes"]:
        netcnt[n] += 1
for p in spins:
    if netcnt[p] == 0:
        warn.append("pin '%s' is not connected to any device" % p)
for n, c in netcnt.items():
    if c == 1 and n not in spins:
        warn.append("net '%s' has only one connection (dangling?)" % n)

# --- per-device parameter sanity
mos = [d for d in sdevs if len(d["nodes"]) == 4]
res = [d for d in sdevs if len(d["nodes"]) == 2]
for d in mos:
    w, l, nf, m, mult, cnt, wf = mos_info(d)
    if m is not None and mult is not None and m != mult:
        warn.append("%s: mult=%s but m=%s (should be equal)" % (d["name"], fmt(mult), fmt(m)))
    if mult is not None and mult != 1 and m is None:
        warn.append("%s: mult=%s but no m= (netgen may count only 1)" % (d["name"], fmt(mult)))
    if nf != 1:
        warn.append("%s: nf=%s (other devices usually nf=1; check)" % (d["name"], fmt(nf)))

# --- odd-one-out: same model, different sizes (breaks symmetric LVS)
bymodel = defaultdict(list)
dummies = [d for d in mos if len(set(d["nodes"])) == 1]
for d in mos:
    if d in dummies:
        continue
    w, l, nf, m, mult, cnt, wf = mos_info(d)
    bymodel[d["model"]].append((d["name"], (wf, l, nf, cnt)))
for model, lst in bymodel.items():
    cfg = Counter(c for _, c in lst)
    if len(cfg) > 1:
        common = cfg.most_common(1)[0][0]
        for name, c in lst:
            if c != common and cfg[c] == 1 and cfg[common] >= 2:
                warn.append("%s differs from the others %s: W/finger=%s L=%s nf=%s count=%s "
                            "(others: W/finger=%s L=%s nf=%s count=%s) -> typo?"
                            % (name, model, *map(fmt, c), *map(fmt, common)))

# dummies (all terminals on one net) should use a normal finger width
for d in dummies:
    w, l, nf, m, mult, cnt, wf = mos_info(d)
    wfs = {mos_info(x)[6] for x in mos if x not in dummies and x["model"] == d["model"]}
    if wfs and wf not in wfs:
        warn.append("%s (dummy): W/finger=%s differs from the real devices (%s)"
                    % (d["name"], fmt(wf), " ".join(fmt(x) for x in sorted(wfs))))

print("=== SPICE CHECK (schematic)")
if warn:
    for w in warn:
        print("  ! " + w)
else:
    print("  no issues found")

# --- size comparison: total fingers per (model, W/finger, L)
def tally(devs):
    t = Counter()
    for d in devs:
        if len(d["nodes"]) == 4:
            w, l, nf, m, mult, cnt, wf = mos_info(d)
            t[(d["model"], round(wf or 0, 3), round(l or 0, 3))] += cnt * nf
        elif len(d["nodes"]) == 2:
            p = d["p"]
            t[(d["model"], round(num(p.get("w"), 0), 3), round(num(p.get("l"), 0), 3))] += num(p.get("m"), 1)
    return t

ts, tl = tally(sdevs), tally(ldevs)
print()
print("=== SIZE COMPARE (fingers / resistors per model, W, L)")
print("  %-34s %8s %8s  %s" % ("model  W  L", "schem", "layout", ""))
for key in sorted(set(ts) | set(tl), key=str):
    a, b = ts.get(key, 0), tl.get(key, 0)
    mark = "" if a == b else "  <-- MISMATCH"
    print("  %-34s %8g %8g%s" % ("%s %g %g" % (key[0].replace("sky130_fd_pr__", ""), key[1], key[2]), a, b, mark))

if len(sys.argv) > 5 and sys.argv[5] == "detail":
    print()
    print("=== SCHEMATIC devices  (name: nodes | W L nf count)")
    for d in sdevs:
        if len(d["nodes"]) == 4:
            w, l, nf, m, mult, cnt, wf = mos_info(d)
            print("  %-6s %-40s W=%s L=%s nf=%s count=%s" % (d["name"], " ".join(d["nodes"]), fmt(w), fmt(l), fmt(nf), fmt(cnt)))
        else:
            print("  %-6s %-40s W=%s L=%s" % (d["name"], " ".join(d["nodes"]), d["p"].get("w", "-"), d["p"].get("l", "-")))
PYEOF

# 6b. connectivity sanity (LVS can pass even if these are wrong)
#   - labeled net with no device: label/pin not connected to the circuit
#   - unlabeled net on devices: wire that has no name (check it is intended)
cat > conn.py << 'PYEOF'
import re, sys
from collections import defaultdict
lay, cell = sys.argv[1], sys.argv[2]
lines, cur = [], ""
for raw in open(lay):
    raw = raw.rstrip("\n")
    if raw.startswith("+"):
        cur += " " + raw[1:]
    else:
        if cur: lines.append(cur)
        cur = raw
if cur: lines.append(cur)
ports, use = [], defaultdict(int)
for l in lines:
    t = l.split()
    if not t: continue
    if t[0].lower() == ".subckt" and t[1] == cell:
        ports = t[2:]; continue
    if t[0][0] in "XMRC":
        n = 5 if t[0][0] in "XM" and len(t) > 5 and "=" not in t[4] else 3
        for x in t[1:n]:
            if "=" not in x: use[x] += 1
print("=== CONNECTIVITY CHECK (layout)")
bad = [p for p in ports if use[p] == 0]
for p in bad:
    print("  ! pin/label '%s' is not connected to any device (floating)" % p)
unl = sorted(n for n in use if re.match(r"^a_n?\d+_n?\d+#?$", n))
print("  unlabeled nets on devices: %d  (compare with the unnamed nets in the schematic)" % len(unl))
for n in unl:
    m = re.match(r"^a_(n?\d+)_(n?\d+)", n)
    x, y = [int(v.replace("n", "-")) * 0.005 for v in m.groups()]
    print("    %-20s (%.1f, %.1f) um" % (n, x, y))
if not bad:
    print("  all pins/labels connect to devices")
PYEOF
python3 conn.py lay.spice "$CELL" > conn.txt 2>&1

# 7. compare with netgen
netgen -batch lvs "lay.spice $CELL" "sch.spice $SCH_CELL" \
  "$PDK/libs.tech/netgen/sky130A_setup.tcl" lvs_report.txt -full > netgen.log 2>&1

echo
echo "=== layout : $GDS_ABS ($CELL)"
echo "=== schem  : $SCH_ABS ($SCH_CELL)"
grep -E "contains [0-9]+ (devices|nets)" netgen.log | tail -2
grep -A1 "Final result" netgen.log
echo
python3 check.py lay.spice sch.spice "$CELL" "$SCH_CELL"
echo
cat conn.txt
echo
if grep -qi "property errors" netgen.log; then
  echo "!!! property errors found"
elif grep -q "Circuits match uniquely" netgen.log; then
  echo ">>> LVS OK"
  exit 0
fi
echo ">>> LVS FAILED  (details: $WORK/lvs_report.txt)"

# ---------- diagnostics ----------
echo
echo "=== PINS"
echo "layout   : $(subckt_pins lay.spice "$CELL")"
echo "schematic: $(subckt_pins sch.spice "$SCH_CELL")"

echo
echo "=== LABELS IN GDS (layer  text  x  y)"
cat > texts.py << EOF
import pya
ly = pya.Layout()
ly.read("flat.gds")
top = ly.cell("$CELL")
for li in ly.layer_indexes():
    for s in top.each_shape(li):
        if s.is_text():
            t = s.text
            print("  %-8s %-16s %9.3f %9.3f" % (ly.get_info(li), t.string[:16], t.x*ly.dbu, t.y*ly.dbu))
EOF
klayout -b -r texts.py < /dev/null 2>/dev/null

echo
echo "=== LAYOUT devices  (count: d g s b model | resistor: a b model w l)"
awk '/^[XRM]/{print $2,$3,$4,$5,$6}' lay.spice | sort | uniq -c

echo
python3 check.py lay.spice sch.spice "$CELL" "$SCH_CELL" detail | sed -n '/=== SCHEMATIC devices/,$p'

echo
UNNAMED=$(grep -o 'a_[n0-9_]*#' lay.spice | sort -u)
if [ -n "$UNNAMED" ]; then
  echo "=== UNNAMED LAYOUT NETS (no label / not connected / shorted); ~coords in um"
  for n in $UNNAMED; do
    # Magic names nets a_<x>_<y># in internal units (0.005 um)
    xy=$(echo "$n" | sed -E 's/a_(n?[0-9]+)_(n?[0-9]+)#/\1 \2/; s/n/-/g')
    printf "  %-18s (%s)\n" "$n" "$(echo $xy | awk '{printf "%.2f, %.2f", $1*0.005, $2*0.005}')"
  done
fi

echo
echo "=== NETGEN pin/property section"
awk '/Subcircuit pins:/{buf=""; f=1} f{buf=buf $0 "\n"} END{printf "%s", buf}' lvs_report.txt | head -30
grep -A3 -i "property error\|delta=" lvs_report.txt | head -20
